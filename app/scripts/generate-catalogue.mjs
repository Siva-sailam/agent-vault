#!/usr/bin/env node
// Generates src/catalogue.ts — the merchant catalogue and mint address the
// front end ships with. Reads ONLY the public-key half of each keypair file
// (bytes 32..64 of Solana's 64-byte keypair JSON format) and discards the
// rest immediately; the private-key half is never held longer than it takes
// to slice past it, never logged, and never written anywhere by this script.
//
// Re-run this whenever the demo keypairs change:
//   node scripts/generate-catalogue.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import bs58 from 'bs58';

const KEYS_DIR = join(homedir(), 'agent-vault', 'keys');

function publicKeyOf(fileName) {
  const bytes = JSON.parse(readFileSync(join(KEYS_DIR, fileName), 'utf8'));
  if (!Array.isArray(bytes) || bytes.length !== 64) {
    throw new Error(`${fileName}: expected a 64-byte Solana keypair file`);
  }
  const publicKeyBytes = Uint8Array.from(bytes.slice(32, 64));
  return bs58.encode(publicKeyBytes);
}

const merchants = [
  { label: 'Noonly', file: 'merchant-noon.json' },
  { label: 'Talabird', file: 'merchant-talabat.json' },
  { label: 'Zomatic', file: 'merchant-zomato.json' },
  { label: 'Kuber Eats', file: 'merchant-ubereats.json' },
].map(({ label, file }) => ({ label, wallet: publicKeyOf(file) }));

const mint = publicKeyOf('demo-usd-mint.json');

const output = `// GENERATED by scripts/generate-catalogue.mjs — do not hand-edit.
// Contains PUBLIC keys only, derived from ~/agent-vault/keys/*.json. No
// private key material is present in this file or was logged while
// generating it.

export type Merchant = {
  label: string;
  /** The merchant's own wallet address (not their Demo USD token account). */
  wallet: string;
};

/** Bank-published merchant catalogue. Fixed list of 4 — matches the
 * program's MAX_MERCHANTS_PER_AGENT. */
export const MERCHANT_CATALOGUE: Merchant[] = ${JSON.stringify(merchants, null, 2)};

/** The "Demo USD" test token created in M5. Decimals: 0. */
export const DEMO_USD_MINT = '${mint}';
`;

writeFileSync(join(import.meta.dirname, '..', 'src', 'catalogue.ts'), output);
console.log(`Wrote src/catalogue.ts with ${merchants.length} merchants + mint address.`);
